const FormattingTasks = async (tasks) => {
    //a: 0, execute: 0, remaining: 6, deadline: 30
    for (let index in tasks)
    {
        tasks[index].a =0
        tasks[index].execute =0
        tasks[index].remaining =tasks[index].e
        tasks[index].deadline =tasks[index].p
    }
    return tasks
}

const sortTask = async (tasksList, sortBy = "deadline") => {
    if(sortBy == "deadline") {
        let sortedTasksByDeadling = tasksList.sort(function (a, b) {
            return a.deadline - b.deadline;
        });
        return sortedTasksByDeadling;
    }
    if(sortBy == "timeShare") {
        let sortedTasksByDeadling = tasksList.sort(function (a, b) {
            return b.timeShare - a.timeShare;
        });
        return sortedTasksByDeadling;
    }
}

const getTasksHyperWindow = async (arrayOfObject) => {
    const input_array = arrayOfObject.map(data => {
        return data.p
    })
    var r1 = 0, r2 = 0;
    var l = input_array.length;
    for (i = 0; i < l; i++) {
        r1 = input_array[i] % input_array[i + 1];
        if (r1 === 0) {
            input_array[i + 1] = (input_array[i] * input_array[i + 1]) / input_array[i + 1];
        } else {
            r2 = input_array[i + 1] % r1;
            if (r2 === 0) {
                input_array[i + 1] = (input_array[i] * input_array[i + 1]) / r1;
            } else {
                input_array[i + 1] = (input_array[i] * input_array[i + 1]) / r2;
            }
        }
    }
    return input_array[l - 1];
}

const getTasksShareInGivenTimeSlice = async (tasksList, deadline, periodStart) => {

    let dataToSend = []
    let noExecuteTasks = []
    for (let task in tasksList) {
        let taskId = tasksList[task].t
        if(tasksListForNotExecute.includes(taskId))
        {
            tasksList[task].processor = "--"
            tasksList[task].timeShare =0
            tasksList[task].remaining = 0
            tasksList[task].execute =0
            noExecuteTasks.push(tasksList[task])

            continue;
        }
        let data = Object.assign({}, tasksList[task])
        let timeShare = data.remaining == 1 ? data.remaining : Math.floor(((data.remaining * (deadline - periodStart)) / (data.deadline - periodStart)))
        data.timeShare = timeShare
        data.remaining = data.remaining - timeShare
        data.execute = data.execute + timeShare
        dataToSend.push(data)
    }
    let sortedTasksByDeadling = await sortTask(dataToSend,"timeShare")

    return [...sortedTasksByDeadling,...noExecuteTasks]
}

