const frequencyRequirement = async (originalTaskSchedule,deadline,i=0) => {

    if (i==0)
    {
        for(let index in originalTaskSchedule)
        {
            originalTaskSchedule[index].nochange = 0
        }
    }

    let sumOfNoChange = 0
    let sum = 0
    for(let index in originalTaskSchedule)
    {
        if(originalTaskSchedule[index].nochange ==1)
        {
            sumOfNoChange = sumOfNoChange + originalTaskSchedule[index].timeShare
        }
        else
        {
            sum = sum + originalTaskSchedule[index].timeShare
        }
    }
    console.log("(deadline * numberOfProcessor)-sumOfNoChange)",((deadline * numberOfProcessor)-sumOfNoChange),sum,sumOfNoChange,deadline);
    let frequencyRequired = sum/((deadline * numberOfProcessor)-sumOfNoChange)
    frequencyRequired = frequencyRequired

    let nearestFrequency = frequencyRequired > 1 ? 1 : await getNearestFrequency(frequencyRequired)

    //let nearestFrequency = 1
    for (let index in originalTaskSchedule)
    {
        if(originalTaskSchedule[index].nochange == 1)
        {
            originalTaskSchedule[index].frequencyToRun = 1
            continue;
        }
        originalTaskSchedule[index].newShare = Math.floor(originalTaskSchedule[index].timeShare/nearestFrequency)
        originalTaskSchedule[index].frequencyToRun = nearestFrequency
        originalTaskSchedule[index].frequencyCalculated = frequencyRequired
    }

    let sumOfNewShare = 0
    for (let index in originalTaskSchedule)
    {
        if(originalTaskSchedule[index].nochange == 1)
        {
            continue;
        }
        sumOfNewShare = sumOfNewShare + originalTaskSchedule[index].timeShare
    }

    if(sumOfNewShare > ((deadline * numberOfProcessor)-sumOfNoChange))
    {
        originalTaskSchedule = originalTaskSchedule.sort(function (a, b) {
            return b.newShare - a.newShare;
        });
        for (let index in originalTaskSchedule)
        {
            if (originalTaskSchedule[index].nochange == 1)
            {
                continue;
            }
            originalTaskSchedule[index].nochange = 1;
            originalTaskSchedule[index].newShare = originalTaskSchedule[index].timeShare;
            break;
        }
        return frequencyRequirement(originalTaskSchedule,deadline,1)
    }
    return originalTaskSchedule;
}

